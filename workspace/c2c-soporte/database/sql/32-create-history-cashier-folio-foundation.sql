-- C2C Soporte - base local historial, cajeros y proyeccion folios
-- Ejecutar conectado a la base local soporte.
-- No ejecutar en produccion.
-- No apunta a public. Crea objetos locales en rr_gestion_soporte.

CREATE TABLE IF NOT EXISTS rr_gestion_soporte.documentos_historial_anual_resumen (
  resumen_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio integer NOT NULL,
  tenant_id uuid NOT NULL,
  rut integer,
  device_id varchar(255),
  tipodocumento integer,
  documentos_emitidos bigint NOT NULL DEFAULT 0,
  primer_folio_emitido integer,
  ultimo_folio_emitido integer,
  primera_emision date,
  ultima_emision date,
  valor_total_documentos bigint NOT NULL DEFAULT 0,
  origen text NOT NULL DEFAULT 'annual_readonly_summary',
  cargado_en timestamp without time zone NOT NULL DEFAULT now(),
  observacion text,
  CONSTRAINT documentos_historial_anual_resumen_unique
    UNIQUE NULLS NOT DISTINCT (anio, tenant_id, rut, device_id, tipodocumento)
);

COMMENT ON TABLE rr_gestion_soporte.documentos_historial_anual_resumen IS
  'Resumen anual historico agregado. No contiene documentos completos.';

CREATE TABLE IF NOT EXISTS rr_gestion_soporte.folios_alerta_config (
  config_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid,
  rut integer,
  document_type integer,
  minimo_folios_warning integer NOT NULL DEFAULT 30000,
  minimo_folios_urgente integer NOT NULL DEFAULT 10000,
  dias_agotamiento_warning integer NOT NULL DEFAULT 30,
  dias_agotamiento_urgente integer NOT NULL DEFAULT 15,
  dias_sin_emision_warning integer NOT NULL DEFAULT 3,
  dias_sin_emision_urgente integer NOT NULL DEFAULT 7,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamp without time zone NOT NULL DEFAULT now(),
  updated_at timestamp without time zone NOT NULL DEFAULT now(),
  CONSTRAINT folios_alerta_config_scope_unique
    UNIQUE (tenant_id, rut, document_type)
);

COMMENT ON TABLE rr_gestion_soporte.folios_alerta_config IS
  'Configuracion local de umbrales para alertas de folios y emision.';

